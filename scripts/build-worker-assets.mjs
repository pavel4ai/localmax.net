#!/usr/bin/env node
/**
 * Generate the two things the Worker cannot compute at runtime.
 *
 * 1. `apps/api/src/generated/validators.mjs` — standalone Ajv validators.
 *    Ajv normally compiles schemas with `new Function`, which Workers forbid. Compiling
 *    ahead of time to plain ES modules gives full JSON Schema validation on the edge with
 *    no eval and no schema-parsing cost per request.
 *
 * 2. `apps/api/src/generated/registry.ts` — the profile and hardware registries, frozen
 *    into the bundle. A submission is checked against the exact profile bytes it claims to
 *    have run, and the profile hash in the manifest must match the hash computed here.
 *
 * Run automatically by `npm run build|dev|deploy|test` in apps/api.
 */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_DIR = join(ROOT, "schemas");
const PROFILE_DIR = join(ROOT, "benchmarks", "profiles");
const OUT_DIR = join(ROOT, "apps", "api", "src", "generated");

const BASE = "https://localmax.net/schemas/";

/** Canonical JSON per RFC 8785 (JCS): sorted keys, no insignificant whitespace. */
function canonicalize(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalize).join(",")}]`;
  const keys = Object.keys(value).sort();
  return `{${keys
    .map((k) => `${JSON.stringify(k)}:${canonicalize(value[k])}`)
    .join(",")}}`;
}

function sha256(text) {
  return "sha256:" + createHash("sha256").update(text, "utf8").digest("hex");
}

// --- 1. validators ---------------------------------------------------------

const ajv = new Ajv({
  strict: false,
  allErrors: true,
  code: { source: true, esm: true, optimize: 2 },
  // Errors are surfaced to a CLI user, so keep them readable.
  verbose: false,
});
addFormats(ajv);

const schemaFiles = readdirSync(SCHEMA_DIR).filter((f) => f.endsWith(".schema.json"));
for (const file of schemaFiles) {
  const schema = JSON.parse(readFileSync(join(SCHEMA_DIR, file), "utf8"));
  ajv.addSchema(schema, BASE + file);
}

const EXPORTS = {
  validateResult: BASE + "result.schema.json",
  validateProfile: BASE + "profile.schema.json",
  validateChallengeRequest: BASE + "api.schema.json#/$defs/challengeRequest",
  validateCreateSubmission: BASE + "api.schema.json#/$defs/createSubmissionRequest",
  validateCompleteSubmission: BASE + "api.schema.json#/$defs/completeSubmissionRequest",
};

const refs = {};
for (const [name, ref] of Object.entries(EXPORTS)) {
  const id = `urn:localmax:${name}`;
  ajv.addSchema({ $id: id, $ref: ref });
  ajv.getSchema(id); // force compile so standaloneCode can find it
  refs[name] = id;
}

mkdirSync(OUT_DIR, { recursive: true });
const code = standaloneCode(ajv, refs);
writeFileSync(
  join(OUT_DIR, "validators.mjs"),
  "// GENERATED by scripts/build-worker-assets.mjs. Do not edit.\n" +
    "/* eslint-disable */\n" +
    code,
);

writeFileSync(
  join(OUT_DIR, "validators.d.mts"),
  `// GENERATED by scripts/build-worker-assets.mjs. Do not edit.
export interface ValidationError {
  instancePath: string;
  schemaPath: string;
  keyword: string;
  message?: string;
  params: Record<string, unknown>;
}
export interface Validator {
  (data: unknown): boolean;
  errors?: ValidationError[] | null;
}
${Object.keys(EXPORTS)
  .map((n) => `export declare const ${n}: Validator;`)
  .join("\n")}
`,
);

// --- 2. registry -----------------------------------------------------------

const profiles = {};
for (const file of readdirSync(PROFILE_DIR).filter((f) => f.endsWith(".json")).sort()) {
  const raw = JSON.parse(readFileSync(join(PROFILE_DIR, file), "utf8"));
  delete raw.$schema; // presentation only, not part of the pinned rules
  const hash = sha256(canonicalize(raw));
  profiles[raw.id] = { ...raw, hash };
}

const hardware = JSON.parse(readFileSync(join(ROOT, "benchmarks", "hardware.json"), "utf8"));

writeFileSync(
  join(OUT_DIR, "registry.ts"),
  `// GENERATED by scripts/build-worker-assets.mjs. Do not edit.
// Source: benchmarks/profiles/*.json and benchmarks/hardware.json
//
// \`hash\` is the SHA-256 of the RFC 8785 canonical form of the profile file with \`$schema\`
// removed. A submitted manifest must carry the same hash, which proves which rules were in
// force for that run and makes a silently edited profile detectable.

export interface ProfileGate {
  metric: string;
  comparator: "lte" | "gte" | "eq";
  value: number;
  source_workload: string;
  reason?: string;
}

export interface ProfileSecondary {
  metric: string;
  label: string;
  unit: string;
  direction?: "higher_is_better" | "lower_is_better";
  source_workload?: string;
}

export interface Profile {
  id: string;
  version: string;
  frozen: boolean;
  published: boolean;
  display_name: string;
  summary?: string;
  category: "llm" | "vision" | "diffusion";
  tier: "entry" | "enthusiast" | "prospector";
  lane: "fp8" | "int4" | "nvfp4" | "bf16";
  hash: string;
  requirements: {
    min_vram_bytes: number;
    min_system_ram_bytes?: number;
    min_disk_bytes?: number;
    min_driver: string;
    min_compute_capability?: string;
    architectures: string[];
    platforms: string[];
    gpu_count?: number[];
    expected_runtime_minutes?: number;
    expected_download_bytes?: number;
  };
  model: Record<string, unknown> & { repository: string; revision: string; precision: string };
  runtime: { name: string; version: string; flags: Record<string, unknown> } & Record<string, unknown>;
  workloads: Array<Record<string, unknown> & { id: string; kind: string }>;
  ranking: {
    metric: string;
    unit: string;
    direction: "higher_is_better" | "lower_is_better";
    source_workload: string;
    secondary?: ProfileSecondary[];
    gates?: ProfileGate[];
  };
  validation: {
    required_artifacts: string[];
    telemetry_interval_ms: number;
    min_telemetry_coverage_pct: number;
    metric_recompute_tolerance_pct?: number;
    max_repeat_cv_pct?: number;
    plausibility?: Record<string, { min: number; max: number }>;
  };
  notes?: string[];
  assets?: Array<Record<string, unknown>>;
  // Carried verbatim from the profile file; nothing in the API reads these.
  [extra: string]: unknown;
}

export interface GpuSpec {
  key: string;
  name: string;
  vendor: string;
  architecture: string;
  compute_capability: string;
  vram_bytes: number;
  memory_bandwidth_gb_s: number;
  default_power_limit_w: number;
  supports_fp8: boolean;
  supports_nvfp4: boolean;
  memory_type: "discrete" | "unified";
  class: string;
  cpu_arch?: string;
  notes?: string[];
  source?: string;
  [extra: string]: unknown;
}

export const PROFILES: Record<string, Profile> = ${JSON.stringify(profiles, null, 2)} as const;

export const PROFILE_IDS = Object.keys(PROFILES);

/**
 * Changes whenever any profile changes. Used in read-cache keys so a deploy cannot keep
 * serving a response built against the previous profile set.
 */
export const REGISTRY_VERSION = ${JSON.stringify(
  sha256(Object.values(profiles).map((p) => p.hash).join("|")).slice(7, 19),
)};

export const TIERS: Record<string, { min_vram_bytes: number; label: string; description: string }> =
  ${JSON.stringify(hardware.tiers, null, 2)};

export const GPUS: GpuSpec[] = ${JSON.stringify(hardware.gpus, null, 2)} as GpuSpec[];

export const GPU_BY_KEY: Record<string, GpuSpec> = Object.fromEntries(
  GPUS.map((g) => [g.key, g]),
);
`,
);

// --- 3. system naming ------------------------------------------------------

const systemNames = JSON.parse(
  readFileSync(join(ROOT, "benchmarks", "system-names.json"), "utf8"),
);

writeFileSync(
  join(OUT_DIR, "system-names.ts"),
  `// GENERATED by scripts/build-worker-assets.mjs. Do not edit.
// Source: benchmarks/system-names.json
//
// A system's label is derived from its public key, so the same machine always gets the same
// name and no label is chosen by, or traceable to, a person. The Python runner derives the
// identical label from the same JSON file, so a contributor sees on their terminal exactly
// what the site will show.

export const SYSTEM_NAMES: readonly string[] = ${JSON.stringify(systemNames.names)};
export const CODE_ALPHABET = ${JSON.stringify(systemNames.alphabet)};
`,
);

// --- 4. released container digests -----------------------------------------

const released = JSON.parse(
  readFileSync(join(ROOT, "containers", "released-images.json"), "utf8"),
);
const digests = (released.images ?? []).map((i) => i.digest).filter(Boolean);

writeFileSync(
  join(OUT_DIR, "images.ts"),
  `// GENERATED by scripts/build-worker-assets.mjs. Do not edit.
// Source: containers/released-images.json
//
// A result reaches Verified only if its container digest is in this list. An empty list
// means no image has been released yet, so every submission is Community until the first
// signed release lands.

export const OFFICIAL_IMAGE_DIGESTS: readonly string[] = ${JSON.stringify(digests, null, 2)};

export const OFFICIAL_IMAGES: ReadonlyArray<{
  image: string;
  tag: string;
  digest: string;
  platform: string;
  released_at: string;
}> = ${JSON.stringify(released.images ?? [], null, 2)};
`,
);

console.log(
  `built ${schemaFiles.length} schemas -> ${Object.keys(EXPORTS).length} validators, ` +
    `${Object.keys(profiles).length} profiles, ${hardware.gpus.length} GPUs, ` +
    `${digests.length} released image digests, ${systemNames.names.length} system names`,
);
